"""Final assembly: intro title card + step clips + optional outro card chained
with xfade (video) + acrossfade (audio), then a finalize pass that overlays a
logo watermark and mixes ducked background music → output/{flow_id}/final-demo.mp4.

Clips merge progressively in pairs — each intermediate is a valid video,
which makes failures debuggable."""

from pathlib import Path

from core.progress import progress_bus
from core.storage import clips_dir, final_video_path
from models.flow import BrandConfig, DemoFlow
from services.branding import hex_to_ffmpeg, logo_path, music_path
from services.ffmpeg import drawtext, ensure_playable, get_dimensions, get_duration, run_ffmpeg

XFADE = 0.4
INTRO_SECONDS = 3.0
OUTRO_SECONDS = 3.5


async def make_title_card(title: str, description: str, out: Path, width: int, height: int,
                          accent: str = "0x7F77DD") -> Path:
    tagline = (description or "A product walkthrough, generated by DemoFlow").strip()[:80]
    ay = height // 2 + 70  # accent bar just under the texts
    vf = (
        drawtext(title[:60] or "Product Demo", fontsize=52, x="(w-text_w)/2", y="(h/2)-60", alpha=0.0, boxborder=1)
        + "," + drawtext(tagline, fontsize=26, x="(w-text_w)/2", y="(h/2)+24", alpha=0.0, boxborder=1)
        + f",drawbox=x=(iw-160)/2:y={ay}:w=160:h=5:color={accent}@0.95:t=fill"
        + ",fade=t=in:st=0:d=0.6,fade=t=out:st=2.4:d=0.6"
    )
    await run_ffmpeg(
        [
            "-f", "lavfi", "-i", f"color=c=0x151c27:s={width}x{height}:r=30:d={INTRO_SECONDS}",
            "-f", "lavfi", "-t", f"{INTRO_SECONDS}", "-i", "anullsrc=channel_layout=stereo:sample_rate=44100",
            "-vf", vf,
            "-map", "0:v", "-map", "1:a",
            "-c:v", "libx264", "-preset", "fast", "-crf", "20", "-pix_fmt", "yuv420p",
            "-c:a", "aac", "-ar", "44100",
            "-t", f"{INTRO_SECONDS}",
            str(out),
        ],
        timeout=120.0,
    )
    return out


async def make_outro_card(brand: BrandConfig, title: str, out: Path,
                          width: int, height: int) -> Path:
    """Closing call-to-action card mirroring the intro: headline + subtext + CTA."""
    accent = hex_to_ffmpeg(brand.color)
    headline = (brand.outro_headline or title or "Thanks for watching").strip()[:60]
    subtext = (brand.outro_subtext or "").strip()[:90]
    cta = (brand.outro_cta or "").strip()[:90]
    parts = [drawtext(headline, fontsize=48, x="(w-text_w)/2", y="(h/2)-70", alpha=0.0, boxborder=1)]
    if subtext:
        parts.append(drawtext(subtext, fontsize=26, x="(w-text_w)/2", y="(h/2)-6", alpha=0.0, boxborder=1))
    parts.append(f"drawbox=x=(iw-160)/2:y={height // 2 + 44}:w=160:h=5:color={accent}@0.95:t=fill")
    if cta:
        parts.append(drawtext(cta, fontsize=30, x="(w-text_w)/2", y="(h/2)+78", alpha=0.0, boxborder=1))
    fade_out = max(0.5, OUTRO_SECONDS - 0.6)
    parts.append(f"fade=t=in:st=0:d=0.6,fade=t=out:st={fade_out:.2f}:d=0.6")
    vf = ",".join(parts)
    await run_ffmpeg(
        [
            "-f", "lavfi", "-i", f"color=c=0x151c27:s={width}x{height}:r=30:d={OUTRO_SECONDS}",
            "-f", "lavfi", "-t", f"{OUTRO_SECONDS}", "-i", "anullsrc=channel_layout=stereo:sample_rate=44100",
            "-vf", vf,
            "-map", "0:v", "-map", "1:a",
            "-c:v", "libx264", "-preset", "fast", "-crf", "20", "-pix_fmt", "yuv420p",
            "-c:a", "aac", "-ar", "44100",
            "-t", f"{OUTRO_SECONDS}",
            str(out),
        ],
        timeout=120.0,
    )
    return out


async def _xfade_pair(first: Path, second: Path, out: Path) -> None:
    first_duration = await get_duration(first)
    fade = min(XFADE, max(0.1, first_duration - 0.2))
    offset = max(0.0, first_duration - fade)
    await run_ffmpeg(
        [
            "-i", str(first), "-i", str(second),
            "-filter_complex",
            f"[0:v][1:v]xfade=transition=fade:duration={fade:.2f}:offset={offset:.2f}[v];"
            f"[0:a][1:a]acrossfade=d={fade:.2f}:c1=tri:c2=tri[a]",
            "-map", "[v]", "-map", "[a]",
            "-c:v", "libx264", "-preset", "fast", "-crf", "20", "-pix_fmt", "yuv420p",
            "-c:a", "aac", "-ar", "44100", "-b:a", "160k",
            str(out),
        ],
        timeout=600.0,
    )


async def _finalize(concat: Path, flow: DemoFlow, out_path: Path,
                    width: int, height: int) -> None:
    """Overlay the logo watermark and mix ducked background music, in one pass.
    With neither, the file is just remuxed with +faststart."""
    logo = logo_path(flow.id) if flow.brand.logo_path else None
    music = music_path(flow.brand.music)

    if logo is None and music is None:
        await run_ffmpeg(["-i", str(concat), "-c", "copy", "-movflags", "+faststart", str(out_path)],
                         timeout=300.0)
        return

    inputs = ["-i", str(concat)]
    if music is not None:
        inputs += ["-stream_loop", "-1", "-i", str(music)]
        music_idx = 1
        logo_idx = 2
    else:
        logo_idx = 1
    if logo is not None:
        inputs += ["-i", str(logo)]

    graph = []
    # Video: optional logo watermark, top-right, ~11% of frame width.
    if logo is not None:
        lw = max(48, int(width * 0.11))
        graph.append(f"[{logo_idx}:v]scale={lw}:-1[lg]")
        graph.append(f"[0:v][lg]overlay=W-w-24:24:format=auto[v]")
        vmap = "[v]"
    else:
        vmap = "0:v"
    # Audio: optional ducked music mixed under the narration.
    if music is not None:
        vol = max(0.0, min(1.0, flow.brand.music_volume))
        graph.append(f"[{music_idx}:a]volume={vol:.3f}[mraw]")
        graph.append("[mraw][0:a]sidechaincompress=threshold=0.02:ratio=6:attack=15:release=500[mduck]")
        graph.append("[0:a][mduck]amix=inputs=2:duration=first:dropout_transition=0,volume=1.4[a]")
        amap = "[a]"
    else:
        amap = "0:a"

    await run_ffmpeg(
        [
            *inputs,
            "-filter_complex", ";".join(graph),
            "-map", vmap, "-map", amap,
            "-c:v", "libx264", "-preset", "fast", "-crf", "20", "-pix_fmt", "yuv420p",
            "-c:a", "aac", "-ar", "44100", "-b:a", "160k",
            "-movflags", "+faststart",
            str(out_path),
        ],
        timeout=600.0,
    )


async def assemble(flow: DemoFlow) -> Path:
    ordered = sorted(flow.steps, key=lambda s: s.order)
    clips = [Path(s.clip_path) for s in ordered if s.clip_path and Path(s.clip_path).exists()]
    if not clips:
        raise RuntimeError("No composed clips found — run /api/generate before /api/render.")

    width, height = await get_dimensions(clips[0])
    accent = hex_to_ffmpeg(flow.brand.color)
    work_dir = clips_dir(flow.id)

    await progress_bus.publish(flow.id, "rendering", "Creating intro title card…", 84)
    intro = await make_title_card(flow.title, flow.description, work_dir / "intro.mp4",
                                  width, height, accent)
    sequence = [intro, *clips]
    if flow.brand.outro_enabled:
        outro = await make_outro_card(flow.brand, flow.title, work_dir / "outro.mp4", width, height)
        sequence.append(outro)

    current = sequence[0]
    for i, nxt in enumerate(sequence[1:], start=1):
        progress_bus.raise_if_cancelled(flow.id)
        await progress_bus.publish(flow.id, "rendering",
                                   f"Blending transition {i}/{len(sequence) - 1}…",
                                   84 + int(i / (len(sequence) - 1) * 12))
        merged = work_dir / f"_assembly_{i:02d}.mp4"
        await _xfade_pair(current, nxt, merged)
        current = merged

    await progress_bus.publish(flow.id, "rendering", "Adding music & branding…", 97)
    out_path = final_video_path(flow.id)
    await _finalize(current, flow, out_path, width, height)
    for tmp in work_dir.glob("_assembly_*.mp4"):
        tmp.unlink(missing_ok=True)
    return out_path
